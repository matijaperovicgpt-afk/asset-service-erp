"""Regression tests for locale-decimal leakage into the WNT-05 yard SVGs.

``config/settings/base.py`` ships ``LANGUAGE_CODE = "sr-latn"`` and Django
5.2 always localises numbers in templates (``USE_L10N`` is gone), so
``{{ decimal }}`` and ``|floatformat`` render ``40,50`` for the sr_Latn
catalog.  Inside an SVG geometry attribute, a JS numeric literal or an
HTML5 ``<input type="number">`` value that is not a number at all:

* ``viewBox="0 0 40,50 25,25"`` - the comma is a legal ``comma-wsp``
  separator in an SVG number list, so this parses as *six* numbers, the
  viewBox needs exactly four, and the browser discards the attribute;
* ``<rect width="4,25">`` - invalid ``<length>``, geometry falls back to
  ``auto`` -> 0 -> a zero-area rectangle, which is why a correctly saved
  asset is invisible;
* ``const LENGTH = 10,50;`` - a ``SyntaxError`` that kills the whole
  click-to-place script;
* ``parseFloat("40,50")`` -> ``40``, which silently shrinks the yard.

``config/settings/test.py`` pins ``LANGUAGE_CODE = "en"``, which is
exactly why the rest of the suite never saw any of this.  Every test here
therefore renders through the Serbian locale explicitly (language cookie
+ ``override_settings`` + ``translation.override``), and an English
control test proves the assertions are locale-driven rather than always
true.

The assertions parse what was rendered (split the viewBox, ``float()``
every token, walk the SVG attributes) instead of matching exact strings,
so any reasonable fix - ``{% localize off %}``, ``|unlocalize``,
``|floatformat:"2u"`` - satisfies them.
"""

import datetime
import json
import re
from decimal import Decimal

from django.conf import settings
from django.contrib.auth import get_user_model
from django.test import TestCase, override_settings
from django.urls import reverse
from django.utils import translation

from apps.cases.models import Case, CaseType, ReportChannel
from apps.cases.tests import build_workflow
from apps.storage.models import (
    StorageAgreement,
    StorageOrientation,
    StorageZone,
)
from apps.storage.services import place_asset

# --- tiny markup/JS scanners -------------------------------------------
# Deliberately regex-level: we only need the numbers back out, and the
# rendered markup is generated by our own templates.

_SVG_RE = re.compile(r"<svg\b.*?</svg>", re.S)
_SCRIPT_RE = re.compile(r"<script\b[^>]*>(.*?)</script>", re.S)
_TAG_RE = re.compile(r"<([a-zA-Z][\w:-]*)\b([^>]*?)/?>", re.S)
_ATTR_RE = re.compile(r"([a-zA-Z_:][\w:.-]*)\s*=\s*\"([^\"]*)\"")
_VIEWBOX_RE = re.compile(r"viewBox\s*=\s*\"([^\"]*)\"")
# `const X = <literal>;` / let / var, capturing the initialiser.
_JS_INIT_RE = re.compile(
    r"\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*([^;\n]+);"
)
_LOOKS_NUMERIC = re.compile(r"^[+-]?\d")
# SVG attributes whose value must be a bare <number>/<length>. `fill`,
# `d`, `text-anchor` and friends are intentionally absent.
_NUMERIC_SVG_ATTRS = frozenset(
    {
        "x", "y", "width", "height", "rx", "ry", "cx", "cy", "r",
        "dx", "dy", "font-size", "stroke-width", "fill-opacity", "opacity",
    }
)
# https://html.spec.whatwg.org/#valid-floating-point-number - anything
# else is wiped to "" by the value sanitisation of <input type=number>.
_HTML5_FLOAT_RE = re.compile(r"^-?\d+(\.\d+)?([eE][+-]?\d+)?$")


def _is_number(token):
    try:
        float(token)
    except (TypeError, ValueError):
        return False
    return True


def _tags(markup):
    """(tag_name, {attr: value}) for every element in ``markup``."""
    return [
        (name.lower(), dict(_ATTR_RE.findall(attrs)))
        for name, attrs in _TAG_RE.findall(markup)
    ]


class SvgNumberAssertionsMixin:
    """Assertions shared by the yard plan and the fit-check page."""

    def svg_blocks(self, html):
        """The yard drawings only - the page also carries the brand icon
        in the navbar, which is literal path data and never at risk."""
        blocks = [
            svg
            for svg in _SVG_RE.findall(html)
            if "yard-svg" in (_tags(svg)[0][1].get("class") or "")
        ]
        self.assertTrue(blocks, "The page rendered no yard <svg> at all.")
        return blocks

    def assertViewBoxIsWellFormed(self, svg):
        """A viewBox must resolve to exactly four numbers.

        Parsed the way a browser does: the SVG grammar treats a comma as
        a ``comma-wsp`` separator, so ``0 0 40,50 25,25`` is six numbers,
        not four, and the whole attribute is thrown away.
        """
        match = _VIEWBOX_RE.search(svg)
        self.assertIsNotNone(match, "The yard <svg> has no viewBox.")
        raw = match.group(1).strip()
        numbers = re.split(r"[\s,]+", raw)
        self.assertEqual(
            len(numbers),
            4,
            'viewBox="%s" resolves to %d numbers, not 4 - the browser '
            "discards it and the yard never gets a user-unit scale "
            "(comma decimal separator leaking from the active locale?)."
            % (raw, len(numbers)),
        )
        for token in numbers:
            self.assertTrue(
                _is_number(token),
                'viewBox="%s" contains the non-numeric token %r.'
                % (raw, token),
            )
        return [float(token) for token in numbers]

    def yard_payload(self, html):
        """The ``#yard-data`` JSON both yard pages hand to the placer."""
        match = re.search(
            r'<script id="yard-data" type="application/json">(.*?)</script>',
            html,
            re.S,
        )
        return json.loads(match.group(1)) if match else []

    def assertSvgGeometryIsNumeric(self, svg):
        """Every geometry attribute in the SVG must be a parseable number."""
        broken = [
            (tag, name, value)
            for tag, attrs in _tags(svg)
            for name, value in attrs.items()
            if name.lower() in _NUMERIC_SVG_ATTRS and not _is_number(value)
        ]
        self.assertEqual(
            broken,
            [],
            "Non-numeric SVG geometry attributes were rendered (an invalid "
            "<length> computes to 0, so the shape is never drawn): %s"
            % broken,
        )

    def assertDataDimensionsSurviveParseFloat(self, svg, width, length):
        """``data-width``/``data-length`` are read with ``parseFloat``.

        ``parseFloat("40,50")`` stops at the comma and quietly returns
        ``40`` - no error, just a yard up to a metre smaller than reality
        for every bounds clamp in the placement script.
        """
        root = _tags(svg)[0][1]
        for attr, expected in (
            ("data-width", width),
            ("data-length", length),
        ):
            raw = root.get(attr)
            self.assertIsNotNone(raw, "The yard <svg> has no %s." % attr)
            self.assertTrue(
                _is_number(raw),
                '%s="%s" is not a number; parseFloat() would truncate it '
                "silently." % (attr, raw),
            )
            self.assertAlmostEqual(
                float(raw),
                float(expected),
                places=2,
                msg='%s="%s" does not round-trip to %s.'
                % (attr, raw, expected),
            )

    def assertJsNumericLiteralsAreValid(self, html):
        """Numeric-looking JS initialisers must actually be JS numbers.

        ``const LENGTH = 10,50;`` is a parse error (the comma opens a new
        binding and ``50`` is not an identifier), so the entire IIFE -
        rotate button, ghost preview, click-to-place - never runs.
        """
        broken = []
        for script in _SCRIPT_RE.findall(html):
            for name, value in _JS_INIT_RE.findall(script):
                value = value.strip()
                if _LOOKS_NUMERIC.match(value) and not _is_number(value):
                    broken.append("%s = %s" % (name, value))
        self.assertEqual(
            broken,
            [],
            "Invalid JS numeric literal(s) rendered - the surrounding "
            "<script> fails to parse and every handler in it dies: %s"
            % broken,
        )

    def rects(self, svg):
        return [attrs for tag, attrs in _tags(svg) if tag == "rect"]

    def assertRectDrawn(self, svg, x, y, width, height):
        """A <rect> with these metre coordinates must actually be drawn."""
        candidates = []
        for attrs in self.rects(svg):
            values = [attrs.get(k) for k in ("x", "y", "width", "height")]
            if any(v is None for v in values):
                continue
            if not all(_is_number(v) for v in values):
                continue
            candidates.append([float(v) for v in values])
        wanted = [float(v) for v in (x, y, width, height)]
        self.assertTrue(
            any(
                all(abs(got - want) < 0.01 for got, want in zip(rect, wanted))
                for rect in candidates
            ),
            "No <rect> was drawn at x=%s y=%s w=%s h=%s. Numerically "
            "parseable rects found: %s. (A rect whose width/height failed "
            "to parse computes to zero area and is invisible - exactly the "
            "reported 'asset saves fine but nothing is drawn' symptom.)"
            % (x, y, width, height, candidates),
        )

    def svg_numbers(self, html):
        """All geometry attribute values, in document order - for
        comparing one locale's render against another's."""
        return [
            (tag, name, value)
            for svg in self.svg_blocks(html)
            for tag, attrs in _tags(svg)
            for name, value in sorted(attrs.items())
            if name.lower() in _NUMERIC_SVG_ATTRS
        ]


class YardPageTestBase(SvgNumberAssertionsMixin, TestCase):
    """Shared fixture: one zone with fractional dimensions and one
    correctly placed asset.

    Fractions matter. ``|floatformat:"-2"`` drops a trailing ``.00``, so
    a whole-metre zone hides the bug; 40.50 x 25.25 does not.
    """

    ZONE_WIDTH = Decimal("40.50")
    ZONE_LENGTH = Decimal("25.25")
    ASSET_LENGTH = Decimal("10.50")
    ASSET_WIDTH = Decimal("4.25")
    POS_X = Decimal("12.50")
    POS_Y = Decimal("4.25")

    def setUp(self):
        self.statuses = build_workflow(CaseType.STORAGE, ["inquiry"])
        self.zone = StorageZone.objects.create(
            name="Open yard",
            width_m=self.ZONE_WIDTH,
            length_m=self.ZONE_LENGTH,
        )
        self.case = Case.objects.create(
            case_type=CaseType.STORAGE,
            report_channel=ReportChannel.PHONE,
            status=self.statuses["inquiry"],
        )
        self.agreement = StorageAgreement.objects.create(
            case=self.case,
            asset_length_m=self.ASSET_LENGTH,
            asset_width_m=self.ASSET_WIDTH,
        )
        # Placed through the real service, so the fixture cannot drift
        # away from what the yard page is supposed to draw.
        place_asset(
            self.agreement,
            self.zone,
            self.POS_X,
            self.POS_Y,
            StorageOrientation.LENGTHWISE,
            datetime.date(2027, 3, 1),
        )
        self.staff = get_user_model().objects.create_user(
            username="yard_l10n", password="demo12345", is_staff=True
        )
        self.client.force_login(self.staff)

    # LENGTHWISE keeps the outline bow-to-exit: breadth across X, length into Y.
    @property
    def asset_rect(self):
        return (
            self.POS_X,
            self.POS_Y,
            self.ASSET_WIDTH,
            self.ASSET_LENGTH,
        )

    def render(self, url, lang, **params):
        """GET ``url`` with ``lang`` genuinely active.

        Belt and braces: the language cookie is what
        ``config.middleware.CookieLocaleMiddleware`` actually reads,
        ``LANGUAGE_CODE`` is its fallback, and ``translation.override``
        covers rendering outside the request cycle.
        """
        self.client.cookies[settings.LANGUAGE_COOKIE_NAME] = lang
        with override_settings(LANGUAGE_CODE=lang), translation.override(lang):
            response = self.client.get(url, params)
        self.assertEqual(response.status_code, 200)
        return response.content.decode()


class StorageLayoutSvgLocaleTests(YardPageTestBase):
    """WNT-05 yard plan ("Raspored u storage") under sr-latn."""

    @property
    def url(self):
        return reverse("backoffice:storage-layout")

    # --- the reported bug ----------------------------------------------

    def test_viewbox_is_well_formed_under_serbian_locale(self):
        html = self.render(self.url, "sr-latn")
        for svg in self.svg_blocks(html):
            width, length = self.assertViewBoxIsWellFormed(svg)[2:]
            self.assertAlmostEqual(width, float(self.ZONE_WIDTH), places=2)
            self.assertAlmostEqual(length, float(self.ZONE_LENGTH), places=2)

    def test_all_svg_geometry_is_numeric_under_serbian_locale(self):
        html = self.render(self.url, "sr-latn")
        for svg in self.svg_blocks(html):
            self.assertSvgGeometryIsNumeric(svg)

    def test_placed_asset_is_actually_drawn_under_serbian_locale(self):
        """The bug's headline symptom: the asset saves, is listed below the
        yard, and is nowhere to be seen inside the SVG."""
        html = self.render(self.url, "sr-latn")
        svg = self.svg_blocks(html)[0]
        self.assertRectDrawn(svg, *self.asset_rect)

    def test_zone_data_attributes_survive_parsefloat_under_serbian_locale(self):
        html = self.render(self.url, "sr-latn")
        for svg in self.svg_blocks(html):
            self.assertDataDimensionsSurviveParseFloat(
                svg, self.ZONE_WIDTH, self.ZONE_LENGTH
            )

    def test_placing_mode_script_has_valid_numeric_literals(self):
        """``?case=`` mode loads the placer and hands it the yard."""
        html = self.render(self.url, "sr-latn", case=self.case.pk)
        self.assertIn("place-form", html)
        self.assertIn('id="yard-data"', html)
        self.assertJsNumericLiteralsAreValid(html)

    def test_placing_mode_footprint_constants_match_the_asset(self):
        """The footprint the placer draws with used to be a JS literal in
        the page (`const LENGTH = 10,50;` - a SyntaxError under sr-latn).
        It now rides on the placement form as data-*, read with
        ``parseFloat``, so it has the same requirement: a bare number.

        (It sat on the script tag briefly. That could only be read back
        with ``document.currentScript``, which is null when htmx inserts
        the script - and this page lives inside the swapped #main.)"""
        html = self.render(self.url, "sr-latn", case=self.case.pk)
        placer = [
            attrs
            for tag, attrs in _tags(html)
            if tag == "form" and "data-length" in attrs
        ]
        self.assertEqual(len(placer), 1, "The placement form is missing.")
        for name, expected in (
            ("data-length", self.ASSET_LENGTH),
            ("data-width", self.ASSET_WIDTH),
        ):
            raw = placer[0].get(name, "").strip()
            self.assertTrue(
                _is_number(raw),
                "%s=%r is not parseable by parseFloat." % (name, raw),
            )
            self.assertAlmostEqual(float(raw), float(expected), places=2)

    def test_placing_mode_yard_payload_is_locale_independent(self):
        """The rules the ghost applies are driven by this payload; a
        localised number in it would silently shrink a yard or a outline."""
        html = self.render(self.url, "sr-latn", case=self.case.pk)
        payload = self.yard_payload(html)
        for zone in payload:
            for key in ("width", "length", "clearance"):
                self.assertTrue(
                    _is_number(zone[key]),
                    "zone %s=%r is not parseable by parseFloat."
                    % (key, zone[key]),
                )
            for asset in zone["assets"]:
                for key in ("x", "y", "w", "h"):
                    self.assertTrue(
                        _is_number(asset[key]),
                        "asset %s=%r is not parseable by parseFloat."
                        % (key, asset[key]),
                    )

    # --- cross-locale invariant ----------------------------------------

    def test_svg_geometry_is_identical_in_serbian_and_english(self):
        """Machine-readable geometry is not human-facing text: switching
        the UI language must not change a single coordinate."""
        serbian = self.svg_numbers(self.render(self.url, "sr-latn"))
        english = self.svg_numbers(self.render(self.url, "en"))
        self.assertEqual(
            serbian,
            english,
            "SVG coordinates differ between locales - number formatting "
            "is leaking into machine-parsed attributes.",
        )

    def test_english_control_render_is_sound(self):
        """Guards the guard: these assertions pass under `en` today, so a
        failure above really is the locale and not a broken template."""
        html = self.render(self.url, "en")
        for svg in self.svg_blocks(html):
            self.assertViewBoxIsWellFormed(svg)
            self.assertSvgGeometryIsNumeric(svg)
        self.assertRectDrawn(self.svg_blocks(html)[0], *self.asset_rect)

    # --- the other half of the fix: do not over-unlocalise -------------

    def test_human_facing_labels_keep_serbian_decimal_comma(self):
        """Only machine-parsed numbers get unlocalised. The zone size in
        the card header and the asset length in the list below the yard
        are read by people and must stay ``40,50``."""
        html = self.render(self.url, "sr-latn")
        outside_svg = _SVG_RE.sub("", html)
        self.assertIn(
            "40,50 x 25,25 m",
            outside_svg,
            "The zone-size card header lost its localised decimal comma - "
            "the fix unlocalised human-facing text too.",
        )
        self.assertIn(
            "10,50 m",
            outside_svg,
            "The asset length in the list under the yard lost its "
            "localised decimal comma.",
        )


class StorageFitCheckSvgLocaleTests(YardPageTestBase):
    """The pre-contract fit-check page shares the yard skeleton and breaks
    identically - plus it feeds two ``<input type="number">`` fields whose
    values decide a green/red "fits here" verdict."""

    @property
    def url(self):
        return reverse("backoffice:storage-fit-check")

    def test_viewbox_is_well_formed_under_serbian_locale(self):
        html = self.render(self.url, "sr-latn")
        for svg in self.svg_blocks(html):
            self.assertViewBoxIsWellFormed(svg)

    def test_all_svg_geometry_is_numeric_under_serbian_locale(self):
        html = self.render(self.url, "sr-latn")
        for svg in self.svg_blocks(html):
            self.assertSvgGeometryIsNumeric(svg)
            self.assertDataDimensionsSurviveParseFloat(
                svg, self.ZONE_WIDTH, self.ZONE_LENGTH
            )

    def test_occupied_footprint_is_actually_drawn_under_serbian_locale(self):
        html = self.render(self.url, "sr-latn")
        self.assertRectDrawn(self.svg_blocks(html)[0], *self.asset_rect)

    def test_trial_footprint_inputs_hold_valid_html5_numbers(self):
        """``?length=8.5`` rendered as ``value="8,5"`` is not a valid
        floating-point number, so the browser sanitises the field to the
        empty string; ``parseFloat("") || 0`` then makes the trial asset
        0 x 0 and every position in every zone reports "fits here"."""
        html = self.render(self.url, "sr-latn", length="8.5", width="3.25")
        values = {}
        for tag, attrs in _tags(html):
            if tag == "input" and attrs.get("id") in ("fit-length", "fit-width"):
                values[attrs["id"]] = attrs.get("value", "")
        self.assertEqual(set(values), {"fit-length", "fit-width"})
        for field, expected in (("fit-length", 8.5), ("fit-width", 3.25)):
            raw = values[field]
            self.assertTrue(
                _HTML5_FLOAT_RE.match(raw),
                '#%s value="%s" is not a valid HTML5 floating-point '
                "number - the browser blanks the field and the fit check "
                "silently evaluates a 0 x 0 asset." % (field, raw),
            )
            self.assertAlmostEqual(float(raw), expected, places=2)

    def test_zone_data_json_is_locale_independent(self):
        """``json_script`` must keep emitting period decimals; the script
        reads them back with ``parseFloat``."""
        html = self.render(self.url, "sr-latn")
        payload = self.yard_payload(html)
        self.assertTrue(payload, "The fit-check page emitted no zone data.")
        assets = [asset for zone in payload for asset in zone["assets"]]
        self.assertTrue(
            assets,
            "The occupied footprint is missing from the client-side fit data.",
        )
        for asset in assets:
            for key in ("x", "y", "w", "h"):
                self.assertTrue(
                    _is_number(asset[key]),
                    "zone data %s=%r is not parseable by parseFloat."
                    % (key, asset[key]),
                )

    def test_svg_geometry_is_identical_in_serbian_and_english(self):
        serbian = self.svg_numbers(self.render(self.url, "sr-latn"))
        english = self.svg_numbers(self.render(self.url, "en"))
        self.assertEqual(serbian, english)

    def test_english_control_render_is_sound(self):
        html = self.render(self.url, "en", length="8.5", width="3.25")
        for svg in self.svg_blocks(html):
            self.assertViewBoxIsWellFormed(svg)
            self.assertSvgGeometryIsNumeric(svg)
        self.assertRectDrawn(self.svg_blocks(html)[0], *self.asset_rect)
